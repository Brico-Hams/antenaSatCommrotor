#!/usr/bin/env python3
"""Vectorise the BricoHams logo (branding/bricohams_horizontal.png) into
single-colour polygons used for PCB silkscreen and 3D-print emboss.

Outputs (deterministic):
  branding/bricohams_polys.json  - contours (with holes) in source pixels for 'mark' and 'lockup'
  cad/bricohams_logo.scad        - OpenSCAD modules bh_mark_2d(w) / bh_lockup_2d(w), width w mm
"""
import json, sys, pathlib
import numpy as np, cv2
from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parents[1]
im = np.array(Image.open(ROOT/'branding/bricohams_horizontal.png').convert('RGB')).astype(int)
dark = (im.sum(axis=2) < 600).astype(np.uint8)

def crop(x0, x1, y0, y1, blank=None):
    m = np.zeros_like(dark); m[y0:y1, x0:x1] = dark[y0:y1, x0:x1]
    if blank:
        bx0, bx1, by0, by1 = blank; m[by0:by1, bx0:bx1] = 0
    return m

masks = {
    'mark':   crop(45, 426, 36, 380),
    # mark + 'bricohams' word; tagline and dots (sub-0.3 mm features) removed
    'lockup': crop(45, 1136, 36, 380, blank=(430, 1136, 290, 380)),
}

def polys(mask, eps=0.8):
    cs, hier = cv2.findContours(mask, cv2.RETR_TREE, cv2.CHAIN_APPROX_NONE)
    out = []
    for i, c in enumerate(cs):
        a = cv2.approxPolyDP(c, eps, True).reshape(-1, 2)
        if len(a) < 3 or abs(cv2.contourArea(a)) < 6:
            continue
        depth, j = 0, hier[0][i][3]
        while j != -1: depth += 1; j = hier[0][j][3]
        out.append({'pts': a.tolist(), 'depth': depth, 'hole': depth % 2 == 1})
    return out

data = {}
for k, m in masks.items():
    ys, xs = np.where(m)
    x0, x1, y0, y1 = int(xs.min()), int(xs.max()), int(ys.min()), int(ys.max())
    data[k] = {'bbox': [x0, y0, x1 + 1, y1 + 1], 'contours': polys(m)}
(ROOT/'branding/bricohams_polys.json').write_text(json.dumps(data))

# OpenSCAD: polygon with holes via paths (even-odd). Y flipped (image y is down).
scad = ['// GENERATED by scripts/make_logo_assets.py from branding/bricohams_horizontal.png - do not edit.',
        '// BricoHams logo, single colour. Width w in mm; origin at lower-left corner of the bounding box.']
for k, d in data.items():
    x0, y0, x1, y1 = d['bbox']; W = x1 - x0
    pts, paths = [], []
    for c in d['contours']:
        idx = []
        for x, y in c['pts']:
            idx.append(len(pts)); pts.append([round((x - x0) / W, 5), round((y1 - y) / W, 5)])
        paths.append(idx)
    scad.append(f'module bh_{k}_2d(w) {{ scale(w) polygon(points={json.dumps(pts)}, paths={json.dumps(paths)}, convexity=10); }}')
    scad.append(f'bh_{k}_aspect = {round((y1 - y0) / W, 5)}; // height / width')
(ROOT/'cad/bricohams_logo.scad').write_text('\n'.join(scad) + '\n')
print({k: (len(d['contours']), d['bbox']) for k, d in data.items()})
